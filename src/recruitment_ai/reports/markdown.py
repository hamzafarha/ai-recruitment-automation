"""Evidence-backed structured report (diagram part 6) as Markdown, for download and PDF export.

Content required by the fit scoring rubric (KB-RR-002, "What every analysis must contain"): the
grade and score; each requirement's status with the supporting CV excerpt; the gaps to explore in
interview; a summary and a proposed action. Plus traceability (KB-RR-001): the knowledge-base
documents used, the model and the date. The decision always stays with a recruiter.
"""

from typing import Any

from recruitment_ai.matching.schemas import MatchReport

STATUS_ICONS = {"met": "Met", "partial": "Partial", "missing": "Missing"}
LEVEL_LABELS = {"demonstrated": "demonstrated", "equivalent": "equivalent", "listed": "listed only",
                "not_evidenced": "not evidenced"}


def _cell(text: Any) -> str:
    return str(text or "—").replace("|", "/").replace("\n", " ")


def report_markdown(report: MatchReport, review: dict[str, Any] | None = None) -> str:
    """The report of one analysis; ``review`` = the recruiter's latest decision, if any."""
    method = {"agent": "Screening agent (LangGraph: CV and HR rules retrieved per requirement, Qwen2.5-7B "
                       "judgement, every claim checked by code)",
              "llm": "AI analysis (Qwen2.5-7B, evidence-checked)"}.get(report.method, "Fast semantic estimate")
    lines = [
        f"# Screening report — {report.candidate_name or 'Candidate'} for {report.job_title}", "",
        f"**Grade:** {report.grade} / 3 — {report.grade_label}",
        f"**Score:** {report.score:g} / 100 (must-have coverage {report.must_coverage:.0%}, "
        f"nice-to-have coverage {report.nice_coverage:.0%})",
        f"**Proposed action:** {report.action_label}",
        f"**Method:** {method}",
        "**Total experience (KB-RR-003):** "
        + (f"{report.total_years:g} years" if report.total_years is not None else "unknown"),
        f"**Date:** {report.created_at:%Y-%m-%d %H:%M} UTC", "",
    ]
    if review:
        lines += ["## Recruiter decision", "",
                  f"**Decision:** {review.get('decision')} by {review.get('reviewer') or 'recruiter'}"
                  + (f" — grade adjusted to {review['adjusted_grade']}" if review.get("adjusted_grade") is not None
                     else ""),
                  *([f"**Interview:** {review['interview_at']}"] if review.get("interview_at") else []),
                  *([f"**Notes:** {review['notes']}"] if review.get("notes") else []), ""]
    lines += ["## Summary", "", report.summary or "—", ""]
    lines += ["## Requirements and evidence", "",
              "| Req. | Requirement | Type | Status | Evidence level | CV excerpt |",
              "|---|---|---|---|---|---|"]
    for a in report.requirements:
        kind = ("must-have" if a.kind == "must" else "nice-to-have") + f", {a.importance}"
        if a.min_years:
            kind += f", {a.min_years:g}+ years"
        level = LEVEL_LABELS[a.level]
        if a.years_found is not None and a.min_years:
            level += f" ({a.years_found:g} years)"
        excerpt = a.evidence or "—"
        if a.evidence and not a.grounded:
            excerpt += " (not found in the CV)"
        if a.evidence_source:
            excerpt += f" [{a.evidence_source}]"
        lines.append(f"| {a.id} | {_cell(a.text)} | {kind} | {STATUS_ICONS[a.status]} | {_cell(level)} | "
                     f"{_cell(excerpt)} |")
    lines.append("")
    for title, items in (("Strengths", report.strengths), ("Gaps to explore in interview", report.gaps),
                         ("Suggested interview questions", report.interview_questions)):
        lines += [f"## {title}", ""] + ([f"- {item}" for item in items] or ["- —"]) + [""]
    if report.knowledge_sources:
        lines += ["## Company rules used (HR knowledge base)", ""]
        lines += [f"- **{k.doc_id}** — {k.title}" + (f" / {k.section}" if k.section else "")
                  for k in report.knowledge_sources]
        lines.append("")
    if report.warnings:
        lines += ["## Warnings", ""] + [f"- {w}" for w in report.warnings] + [""]
    lines += ["---", "",
              f"Generated by AI Recruitment Automation ({report.model or 'model'}"
              + (f", {report.seconds:g} s" if report.seconds else "") + "). "
              "This analysis supports a recruiter: it never makes the hiring decision (KB-RR-001). "
              "\"Not evidenced\" means the CV does not mention it, not that the candidate lacks it."]
    return "\n".join(lines) + "\n"
